"""Render a plan as Markdown for download."""

from __future__ import annotations

from utsav.core.budget import label
from utsav.core.models import Plan, TaskStatus, format_money


def _md(text: str) -> str:
    """Neutralise Markdown/HTML control characters in user-provided text."""
    for ch in "\\`*_{}[]<>#|":
        text = text.replace(ch, "\\" + ch)
    return text.replace("\n", " ")


def to_markdown(plan: Plan) -> str:
    p, b, cur = plan.profile, plan.budget, plan.budget.currency
    event = p.event_type.value.replace("_", " ").title()
    out = [
        f"# {event} plan — {p.event_date:%d %B %Y}",
        "",
        f"- **Location:** {_md(p.location)} ({p.setting.value})",
        f"- **Guests:** {p.guest_count} ({plan.scale.value})",
        f"- **Budget:** {format_money(b.total_minor, cur)} "
        f"({format_money(b.per_head_minor, cur)} per guest, {b.catering_style.value} catering)",
        f"- **Lead time:** {plan.timeline.lead_time_class.value} — {plan.timeline.reason}",
    ]
    if p.vibe:
        out.append(f"- **Vibe:** {_md(p.vibe)}")
    if p.dietary:
        out.append("- **Dietary:** " + ", ".join(d.value.replace("_", " ") for d in p.dietary))
    out.append(f"\n_Generated by utsav.ai on {plan.generated_on:%d %b %Y}. "
               "Amounts are illustrative defaults, not quotes._\n")  # fmt: skip

    out += ["## Budget", "", "| Category | Amount | Share | Why |", "|---|---:|---:|---|"]
    out += [
        f"| {label(line.category)} | {format_money(line.amount_minor, cur)} | "
        f"{line.percent:g}% | {_md(line.reason)} |"
        for line in b.lines
    ]
    out += ["", "## Timeline", ""]
    for m in plan.timeline.milestones:
        flags = [f for f, on in (("critical", m.is_critical), ("late", m.late_booking),
                                 ("optional", m.optional)) if on]  # fmt: skip
        tag = f" _({', '.join(flags)})_" if flags else ""
        out.append(f"- **{m.due_date:%d %b %Y}** — {m.title}{tag}")
    out += ["", "## Checklist", ""]
    for t in plan.checklist.items:
        box = "x" if t.status is TaskStatus.DONE else " "
        out.append(f"- [{box}] {_md(t.title)}{' **(critical)**' if t.is_critical else ''}")
    if plan.risks:
        out += ["", "## Risks", ""]
        out += [f"- **{r.severity.value.upper()}:** {r.message} _{r.reason}_" for r in plan.risks]
    return "\n".join(out) + "\n"
